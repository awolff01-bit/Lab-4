def divisible_by_m(n,m):
  """
  ## add to this as well as the doctests below

  >>> divisible_by_m(3,2)
  False
  >>> divisible_by_m(0,4)
  True
  >>> divisible_by_m(-6, 2)
  True
  >>> divisible_by_m(10,5)
  True
  >>> divisible_by_m(7,3)
  False
  """
  if n%m==0:
    return True
  else:
    return False
  
  
  
